const { contextBridge, ipcRenderer } = require('electron');
const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('api', {
  channel: call('channel'),
  channelCached: call('channel-cached'),
  channelMore: call('channel-more'),
  feed: call('feed'),
  feedCached: call('feed-cached'),
  feedMore: call('feed-more'),
  search: call('search'),
  videoInfo: call('video-info'),
  play: call('play'),
  download: call('download'),
  openExternal: call('open-external'),
  copyText: call('copy-text'),
  getGuard: call('guard:get'),
  resetGuard: call('guard:reset'),
  onPlayReport: (fn) => ipcRenderer.on('play-report', (_e, r) => fn(r)),
  ytdlpStatus: call('ytdlp:status'),
  ytdlpCheck: call('ytdlp:check'),
  installFfmpeg: call('ffmpeg:install'),
  onYtdlpStatus: (fn) => ipcRenderer.on('ytdlp-status', (_e, s) => fn(s)),
  onFfmpegProgress: (fn) => ipcRenderer.on('ffmpeg-progress', (_e, p) => fn(p)),
  showFile: call('show-file'),
  onDownloadProgress: (fn) => ipcRenderer.on('download-progress', (_e, p) => fn(p)),
  getFavorites: call('favorites:get'),
  setFavorites: call('favorites:set'),
  getPlaylists: call('playlists:get'),
  setPlaylists: call('playlists:set'),
  getPrefs: call('prefs:get'),
  setPrefs: call('prefs:set'),
});
